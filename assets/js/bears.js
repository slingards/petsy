/* ==========================
   HELPERS
========================== */

function formatBearPrice(bear){

    if(
        bear.displayPrice
    ){

        return bear.displayPrice;

    }

    return (
        "$" +
        Number(
            bear.price || 0
        ).toLocaleString()
    );

}


function getBearButtonText(bear){

    if(
        bear.checkoutEnabled === false
    ){

        return "Institutional Enquiry";

    }

    return "Start Request";

}


function getBearButtonClass(bear){

    if(
        bear.checkoutEnabled === false
    ){

        return "institutional-enquiry-btn";

    }

    return "add-cart-btn";

}


