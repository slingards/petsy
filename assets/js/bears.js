/* ==========================
   SEARCH AND FILTER
========================== */

function filterBears(){

    const searchTerm =
    searchInput
    ?
    searchInput.value
    .trim()
    .toLowerCase()
    :
    "";

    const selectedCategory =
    bearFilter
    ?
    bearFilter.value
    :
    "all";

    const filteredBears =
    bears.filter(
        bear => {

            const searchableText = `
                ${bear.name}
                ${bear.scientificName}
                ${bear.category}
                ${bear.subCategory}
                ${bear.location}
                ${bear.description}
            `.toLowerCase();

            const searchMatch =
            searchableText.includes(
                searchTerm
            );

            const categoryMatch =
            selectedCategory === "all" ||
            bear.category === selectedCategory ||
            bear.subCategory === selectedCategory;

            return (
                searchMatch &&
                categoryMatch
            );

        }
    );

    renderBears(
        filteredBears
    );

    if(
        resultsCount
    ){

        resultsCount.textContent =
        `${filteredBears.length} Regulated Profiles`;

    }

}


if(
    searchInput
){

    searchInput.addEventListener(
        "input",
        filterBears
    );

}


if(
    bearFilter
){

    bearFilter.addEventListener(
        "change",
        filterBears
    );

}


